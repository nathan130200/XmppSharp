using XmppSharp.Attributes;

namespace XmppSharp.Protocol;

/// <summary>
/// Describes types of message stanza.
/// </summary>
public enum MessageType : byte
{
	/// <summary>
	/// An error has occurred related to a previous message sent by the sender.
	/// </summary>
	[XmppEnumMember("error")]
	Error,

	/// <summary>
	/// The message is a single message that is sent outside the context of a one-to-one conversation or groupchat, and to which it is expected that the recipient will reply.
	/// </summary>
	[XmppEnumMember("normal")]
	Normal,

	/// <summary>
	/// The message is probably generated by an automated service that delivers or broadcasts content.
	/// </summary>
	[XmppEnumMember("headline")]
	Headline,

	/// <summary>
	/// The message is sent in the context of a one-to-one chat conversation.
	/// </summary>
	[XmppEnumMember("chat")]
	Chat,

	/// <summary>
	/// The message is sent in the context of a multi-user chat environment.
	/// </summary>
	[XmppEnumMember("groupchat")]
	GroupChat
}
